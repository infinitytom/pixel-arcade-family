// Run with NODE_PATH pointing to a Playwright installation.
const { chromium } = require('playwright');
const fs = require('fs');
const path = require('path');
(async () => {
  const browser = await chromium.launch({channel:process.env.BROWSER_CHANNEL || 'msedge',headless:true, args:['--autoplay-policy=no-user-gesture-required']});
  const page = await browser.newPage({viewport:{width:1600,height:1000},deviceScaleFactor:1});
  const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:18892/library/');
  await page.waitForFunction(()=>document.querySelector('#count').textContent.includes('0'));
  await page.screenshot({path:'docs/empty.png'});
  await page.goto('http://127.0.0.1:18891/library/');
  await page.waitForFunction(()=>document.querySelectorAll('.card').length>0);
  await page.waitForTimeout(1000);
  await page.screenshot({path:'docs/library.png'});
  const count=await page.locator('#count').textContent();
  await page.locator('#search').fill('dino.zip');
  await page.locator('.cover').first().click();
  await page.waitForTimeout(500);
  await page.screenshot({path:'docs/detail.png'});
  await page.locator('#save').click();
  await page.locator('.close').click();
  await page.locator('[data-view="favorite"]').click();
  if(await page.locator('.card').count()!==1) throw Error('Favorite failed');
  await page.reload();
  await page.waitForFunction(()=>document.querySelectorAll('.card').length>0);
  await page.locator('[data-view="favorite"]').click();
  if(await page.locator('.card').count()!==1) throw Error('Favorite persistence failed');
  await page.locator('.cover').first().click();
  await page.locator('#play').click();
  await page.waitForTimeout(1500);
  console.log('Game page text:', await page.locator('body').innerText());
  console.log('Buttons:', await page.locator('button').allTextContents());
  await page.screenshot({path:'test-results/game-before.png'});
  const start=page.locator('.ejs_start_button');
  if(await start.count()) await start.click();
  await page.waitForTimeout(12000);
  await page.screenshot({path:'test-results/game-after.png'});
  console.log('Game after:',(await page.locator('body').innerText()).slice(0,1200));
  console.log('Canvas:',await page.locator('canvas').count());
  const mobile=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1});
  await mobile.goto('http://127.0.0.1:18892/library/');
  await mobile.waitForTimeout(500);
  const overflow=await mobile.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1);
  if(overflow) throw Error('Mobile page overflow');
  await mobile.screenshot({path:'test-results/mobile.png'});
  fs.writeFileSync('test-results/browser.json',JSON.stringify({count,errors,mobileOverflow:overflow},null,2));
  if(errors.length) throw Error('Browser errors: '+errors.join('; '));
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
